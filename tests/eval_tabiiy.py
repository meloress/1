IZLAR = [
    (r"[—–]", "uzun tire"),
    (r"(?i)\balbatta\b", "«albatta»"),
    (r"(?i)hurmatli|qadrli", "rasmiy murojaat"),
    (r"(?i)(savol|savollar)(ingiz)? bo'lsa|murojaat qiling|bemalol yozing|yana (biror )?narsa",
     "yakunlovchi taklif"),
    (r"(?i)xursandman|mamnunman|yordam bera|xizmatingizda", "yordamchi ohangi"),
    (r"!.*!", "ko'p undov"),
    (r";", "nuqtali vergul"),
]


def izlar(tarix: list, matn: str) -> list:
    t = nor(matn)
    topildi = [nom for rx, nom in IZLAR if re.search(rx, t, re.M)]
    oxirgi = tarix[-1][1]
    if len(tarix) > 1 and re.search(r"(?i)^(assalom|salom|здравств)", t):
        topildi.append("suhbat o'rtasida qayta salom")
    if len(t) > max(60, 4 * len(oxirgi)):
        topildi.append(f"uzun ({len(t)} belgi, savol {len(oxirgi)})")
    return topildi


HAKAM = (
    "You judge whether a Telegram/Instagram Direct reply was typed by a real small-shop "
    "owner in Uzbekistan on their phone, or generated by an AI/bot. Locals write "
    "casually: short, often lowercase, few emoji, colloquial numbers («80 ming»), no "
    "customer-service phrases. Reply ONLY JSON: {\"ball\": 1-10 (10 = certainly a "
    "human owner), \"izlar\": [short reasons it looks like a bot, in Uzbek]}.")


async def hakam(tarix: list, matn: str) -> tuple:
    suhbat = "\n".join(f"{'MIJOZ' if r == 'user' else 'SOTUVCHI'}: {m}" for r, m in tarix)
    r = await openai_client.responses.create(
        model=HAKAM_MODEL, instructions=HAKAM, store=False,
        input=f"{suhbat}\nSOTUVCHI (baholanadigan javob): {matn}")
    try:
        d = json.loads(re.search(r"\{.*\}", r.output_text, re.S).group(0))
        return int(d.get("ball", 0)), d.get("izlar") or []
    except Exception:
        return 0, ["hakam javobi o'qilmadi"]


async def bitta(tarix: list, uslub: dict | None) -> str:
    oldingi = [{"role": r, "content": m} for r, m in tarix[:-1]]

    async def tarix_f(*a, **k):
        return list(oldingi)

    async def hech(*a, **k):
        return None
    ai.safe_get_chat_history = tarix_f
    ai.safe_history_summary_message = hech
    ai._token_saqla = hech
    yoriq = b.mijoz_yoriqnomasi(BIZNES, avtomat=True, uslub=uslub, ism="Olimjon")
    return await b._model(tarix[-1][1], 424242, -1, 1, biznes_yoriqnoma=yoriq,
                          javob_formati=ai.BIZNES_SXEMA)


async def main():
    takror = int(sys.argv[sys.argv.index("--takror") + 1]) if "--takror" in sys.argv else 1
    qiymat = {sys.argv.index("--takror") + 1} if "--takror" in sys.argv else set()
    arg = [a for i, a in enumerate(sys.argv) if i and not a.startswith("--") and i not in qiymat]
    holatlar = [s for s in S if not arg or any(a in s[0] for a in arg)]
    jami = {}
    natija = []
    for nom_u, uslub in (("uslubsiz", None), ("uslubli", USLUB)):
        ballar, izli = [], 0
        for hid, tarix in holatlar:
            for _ in range(takror):
                try:
                    tur, matn, _, _ = qaror(await bitta(tarix, uslub), tarix[-1][1])
                except Exception as e:
                    print(f"XATO {hid}: {e}")
                    continue
                iz = izlar(tarix, matn)
                ball, sabab = await hakam(tarix, matn)
                ballar.append(ball)
                izli += bool(iz)
                natija.append({"uslub": nom_u, "id": hid, "qaror": tur, "matn": matn,
                               "izlar": iz, "ball": ball, "hakam": sabab})
                print(f"{nom_u:8} {hid:14} {ball:>2}/10 [{tur}] {matn[:90]!r}"
                      + (f"  ← {', '.join(iz)}" if iz else "")
                      + (f"  | hakam: {'; '.join(sabab)[:120]}" if ball < 7 else ""))
        jami[nom_u] = (sum(ballar) / max(1, len(ballar)), izli, len(ballar))
    print()
    for nom_u, (ort, izli, n) in jami.items():
        print(f"{nom_u}: hakam o'rtacha {ort:.1f}/10, izli javob {izli}/{n}")
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".eval_tabiiy_oxirgi.json"),
              "w", encoding="utf-8") as f:
        json.dump(natija, f, ensure_ascii=False, indent=1)

if __name__ == "__main__":
    asyncio.run(main())
